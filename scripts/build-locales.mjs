// Builds src/shared/locales.js from scripts/locales.tsv (one row per English
// interface string, one column per language). Edit the TSV, then run
//   node scripts/build-locales.mjs
// British English is derived from American spelling; Lakota is a short,
// hand-kept list below (see the note there).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const rows = fs.readFileSync(path.join(root, 'scripts/locales.tsv'), 'utf8').split('\n').filter(Boolean).map((l) => l.split('\t'));
const [head, ...data] = rows;
const langs = head.slice(1);
const out = {};
for (const l of langs) out[l] = {};
for (const r of data) {
  if (r.length !== head.length) throw new Error(`Row "${r[0]}" has ${r.length} columns, expected ${head.length}`);
  langs.forEach((l, i) => { if (r[i + 1] && r[i + 1] !== r[0]) out[l][r[0]] = r[i + 1]; });
}
// Counts, in each language. {n} is the number.
const COUNTS = {
  de: ['{n} Wörter', '{n} Seiten', '{n} Karten', '{n} Ereignisse', '{n} Karte', '{n} Ereignis', '{n} Fehler'],
  fr: ['{n} mots', '{n} pages', '{n} cartes', '{n} événements', '{n} carte', '{n} événement', '{n} problèmes'],
  it: ['{n} parole', '{n} pagine', '{n} schede', '{n} eventi', '{n} scheda', '{n} evento', '{n} problemi'],
  ru: ['{n} сл.', '{n} стр.', 'карточек: {n}', 'событий: {n}', 'карточек: {n}', 'событий: {n}', 'ошибок: {n}'],
  uk: ['{n} сл.', '{n} стор.', 'карток: {n}', 'подій: {n}', 'карток: {n}', 'подій: {n}', 'помилок: {n}'],
  pl: ['{n} sł.', '{n} str.', 'karty: {n}', 'wydarzenia: {n}', 'karty: {n}', 'wydarzenia: {n}', 'problemy: {n}'],
  ja: ['{n} 語', '{n} ページ', 'カード {n} 枚', '出来事 {n} 件', 'カード {n} 枚', '出来事 {n} 件', '問題 {n} 件'],
  zh: ['{n} 字', '{n} 页', '{n} 张卡片', '{n} 个事件', '{n} 张卡片', '{n} 个事件', '{n} 个问题'],
  id: ['{n} kata', '{n} halaman', '{n} kartu', '{n} peristiwa', '{n} kartu', '{n} peristiwa', '{n} masalah'],
  es: ['{n} palabras', '{n} páginas', '{n} tarjetas', '{n} eventos', '{n} tarjeta', '{n} evento', '{n} problemas'],
  ko: ['{n}단어', '{n}페이지', '카드 {n}개', '사건 {n}개', '카드 {n}개', '사건 {n}개', '문제 {n}개'],
  ms: ['{n} perkataan', '{n} halaman', '{n} kad', '{n} peristiwa', '{n} kad', '{n} peristiwa', '{n} masalah'],
  vi: ['{n} từ', '{n} trang', '{n} thẻ', '{n} sự kiện', '{n} thẻ', '{n} sự kiện', '{n} lỗi'],
};
const COUNT_KEYS = ['{n} words', '{n} pages', '{n} cards', '{n} events', '{n} card', '{n} event', '{n} problems'];
for (const [l, list] of Object.entries(COUNTS)) list.forEach((v, i) => { out[l][COUNT_KEYS[i]] = v; });
// Lakota (Lakȟótiyapi): only a few everyday words so far. Software terms in
// Lakota should come from fluent speakers and language programs, not guesses —
// everything else stays in English until reviewed translations are added here.
out.lkt = { Book: 'Wówapi', Library: 'Wówapi Thípi', Write: 'Owá', Today: 'Lé aŋpétu kiŋ' };
// British English: American spellings in the interface, respelled.
const GB = [[/\bColor/g, 'Colour'], [/\bcolor/g, 'colour'], [/\bCenter/g, 'Centre'], [/\bcenter/g, 'centre'], [/\bAnalyz/g, 'Analys'], [/\banalyz/g, 'analys'], [/\bOrganiz/g, 'Organis'], [/\borganiz/g, 'organis'], [/\bGray\b/g, 'Grey'], [/\bgray\b/g, 'grey'], [/\bFavorite/g, 'Favourite'], [/\bfavorite/g, 'favourite'], [/\bAcknowledgments\b/g, 'Acknowledgements'], [/\bCatalog\b/g, 'Catalogue']];
out['en-GB'] = {};
for (const r of data) { let s = r[0]; for (const [a, b] of GB) s = s.replace(a, b); if (s !== r[0]) out['en-GB'][r[0]] = s; }

const js = `// Generated by scripts/build-locales.mjs from scripts/locales.tsv — edit those, not this.\nexport const LOCALES = ${JSON.stringify(out, null, 0).replace(/\],"/g, '],\n"').replace(/\},"/g, '},\n"')};\n`;
fs.writeFileSync(path.join(root, 'src/shared/locales.js'), js);
console.log(`locales: ${data.length} strings × ${langs.length + 2} languages`);
